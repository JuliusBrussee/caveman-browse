#!/usr/bin/env node
// Regenerates bin/binary-installer.generated.mjs + bin/release.generated.mjs
// from the vendored installer source and the pinned release metadata.
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const release = readFileSync(join(root, "BINARY_RELEASE"), "utf8").trim();
const publicKey = readFileSync(join(root, "BINARY_SIGNING_PUBKEY.pub"), "utf8");
// Signed binaries are published on the caveman monorepo releases; repo-owned
// releases require the release signing key and are a tracked follow-up.
const releaseBase = "https://github.com/JuliusBrussee/caveman/releases/download";
writeFileSync(join(root, "bin", "release.generated.mjs"), `// Generated by scripts/gen-installer.mjs. Do not edit.
export const BINARY_RELEASE = ${JSON.stringify(release)};
export const BINARY_RELEASE_BASE_DEFAULT = ${JSON.stringify(releaseBase)};
export const BINARY_SIGNING_PUBKEY = ${JSON.stringify(publicKey)};
`);
copyFileSync(join(root, "scripts", "installer-source.mjs"), join(root, "bin", "binary-installer.generated.mjs"));
console.log(`generated installer for ${release}`);
